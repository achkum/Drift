/** Deterministic channel URL, the way Takeout writes it. */
export function channelUrl(name: string): string {
  const slug = name.normalize('NFD').replace(/\p{M}+/gu, '').replace(/[^A-Za-z0-9]/g, '');
  return `https://www.youtube.com/channel/UC${slug}`;
}

// Long tail of topic-neutral channel names ("Northbound Media"), so the feed does not only
// serve the handful of named channels above. Each topic gets its own disjoint slice.
const TAIL_A = ['Blue', 'North', 'Urban', 'Open', 'Hidden', 'Bright', 'Little', 'Wild', 'Quiet', 'Golden', 'Nordic', 'Paper', 'Copper', 'Velvet'];
const TAIL_B = ['Lens', 'Studio', 'Room', 'Media', 'Talks', 'Clips', 'Desk', 'Corner', 'Lab', 'Signal', 'House', 'Works', 'Frame', 'Bureau'];
const TAIL: string[] = TAIL_A.flatMap((a, i) => TAIL_B.map((b, j) => ({ name: `${a} ${b}`, k: (i * 5 + j * 3) % 196 }))).sort((x, y) => x.k - y.k || x.name.localeCompare(y.name)).map((x) => x.name);
const TAIL_PER_TOPIC = 8;

/** Channels the feed serves for a topic, most served first: the named channels, then a neutral long tail. */
export function servedChannels(topic: TopicId): string[] {
  const i = Object.keys(POOLS).indexOf(topic);
  return [...POOLS[topic].channels, ...TAIL.slice(i * TAIL_PER_TOPIC, (i + 1) * TAIL_PER_TOPIC)];
}
